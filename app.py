# --------------------------------------------------------------------------- DB
def get_db():
    if "db" not in g:
        g.db = engine.connect()
    return g.db


@app.teardown_appcontext
def close_db(_exc):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    id_column = (
        "id INTEGER PRIMARY KEY AUTOINCREMENT"
        if engine.dialect.name == "sqlite"
        else "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    schema = (
        f"""CREATE TABLE IF NOT EXISTS products (
            {id_column},
            name TEXT NOT NULL,
            category TEXT NOT NULL,
            price INTEGER NOT NULL,
            description TEXT NOT NULL,
            color TEXT NOT NULL,
            shape TEXT NOT NULL,
            stock INTEGER NOT NULL DEFAULT 0
        )""",
        """CREATE TABLE IF NOT EXISTS orders (
            id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT NOT NULL,
            address TEXT NOT NULL,
            total INTEGER NOT NULL,
            created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        f"""CREATE TABLE IF NOT EXISTS order_items (
            {id_column},
            order_id TEXT NOT NULL REFERENCES orders(id),
            product_id INTEGER NOT NULL REFERENCES products(id),
            quantity INTEGER NOT NULL,
            unit_price INTEGER NOT NULL
        )""",
    )
    with engine.begin() as db:
        for statement in schema:
            db.execute(text(statement))
        if db.execute(text("SELECT COUNT(*) FROM products")).scalar_one() == 0:
            db.execute(
                text(
                    "INSERT INTO products "
                    "(name, category, price, description, color, shape, stock) "
                    "VALUES (:name, :category, :price, :description, :color, :shape, :stock)"
                ),
                [
                    dict(zip(("name", "category", "price", "description", "color", "shape", "stock"), product))
                    for product in SEED_PRODUCTS
                ],
            )


