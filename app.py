@app.get("/api/categories")
def categories():
    rows = get_db().execute(text("SELECT DISTINCT category FROM products ORDER BY category")).mappings().all()
    return jsonify([r["category"] for r in rows])


@app.get("/api/products")
def list_products():
    q = request.args.get("q", "").strip()
    category = request.args.get("category", "").strip()
    sort = request.args.get("sort", "featured")

    sql = "SELECT * FROM products WHERE 1=1"
    params = {}
    if q:
        sql += " AND (LOWER(name) LIKE LOWER(:query) OR LOWER(description) LIKE LOWER(:query))"
        params["query"] = f"%{q}%"
    if category and category != "All":
        sql += " AND category = :category"
        params["category"] = category

    order = {
        "price_asc": "price ASC",
        "price_desc": "price DESC",
        "name": "LOWER(name) ASC",
    }.get(sort, "id ASC")
    sql += f" ORDER BY {order}"  # `order` comes from a fixed dict, never from user input

    rows = get_db().execute(text(sql), params).mappings().all()
    return jsonify([dict(r) for r in rows])


@app.get("/api/products/<int:product_id>")
def get_product(product_id):
    row = get_db().execute(
        text("SELECT * FROM products WHERE id = :id"), {"id": product_id}
    ).mappings().first()
    if row is None:
        return jsonify(error="Product not found."), 404
    return jsonify(dict(row))


@app.post("/api/checkout")
def checkout():
    data = request.get_json(silent=True) or {}
    customer = data.get("customer") or {}
    items = data.get("items") or []

    name = str(customer.get("name", "")).strip()
    email = str(customer.get("email", "")).strip()
    address = str(customer.get("address", "")).strip()

    if not name:
        return jsonify(error="Enter your name."), 400
    if not EMAIL_RE.match(email):
        return jsonify(error="Enter a valid email address."), 400
    if len(address) < 8:
        return jsonify(error="Enter your full delivery address."), 400
    if not isinstance(items, list) or not items:
        return jsonify(error="Your cart is empty."), 400

    db = get_db()
    try:
        with db.begin():
            lines, total = [], 0
            lock_clause = " FOR UPDATE" if engine.dialect.name == "postgresql" else ""
            for item in items:
                try:
                    pid, qty = int(item["id"]), int(item["qty"])
                except (KeyError, TypeError, ValueError):
                    raise ValueError("Your cart has an invalid item.")
                if qty < 1 or qty > 99:
                    raise ValueError("Quantities must be between 1 and 99.")

                product = db.execute(
                    text(f"SELECT * FROM products WHERE id = :id{lock_clause}"), {"id": pid}
                ).mappings().first()
                if product is None:
                    raise ValueError("An item in your cart no longer exists.")
                if product["stock"] < qty:
                    raise ValueError(f"Only {product['stock']} left of {product['name']}.")

                # Price always comes from the database, never from the browser.
                total += product["price"] * qty
                lines.append((pid, qty, product["price"]))

            order_id = "ORD-" + uuid.uuid4().hex[:8].upper()
            db.execute(
                text("INSERT INTO orders (id, name, email, address, total) "
                     "VALUES (:id, :name, :email, :address, :total)"),
                {"id": order_id, "name": name, "email": email, "address": address, "total": total},
            )
            for pid, qty, unit_price in lines:
                db.execute(
                    text("INSERT INTO order_items (order_id, product_id, quantity, unit_price) "
                         "VALUES (:order_id, :product_id, :quantity, :unit_price)"),
                    {"order_id": order_id, "product_id": pid, "quantity": qty, "unit_price": unit_price},
                )
                db.execute(
                    text("UPDATE products SET stock = stock - :quantity WHERE id = :id"),
                    {"quantity": qty, "id": pid},
                )
    except ValueError as exc:
        return jsonify(error=str(exc)), 400
    except Exception:
        app.logger.exception("Checkout failed")
        return jsonify(error="Something went wrong. Try again in a moment."), 500

    return jsonify(order_id=order_id, total=total), 201


